    q, q1, q2, qD = xA

    return (
        "["
        + pretty_estimate(q)
        + ", "
        + pretty_estimate(q1)
        + ",\n"
        + pretty_estimate(q2)
        + ", "
        + pretty_estimate(qD)
        + "]"
    )


