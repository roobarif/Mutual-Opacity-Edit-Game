# 10. VISUALIZE OBSERVER
# ============================================================

def visualize_observer(
    observer_states,
    observer_transitions,
    initial_state,
    filename
):

    dot = Digraph(
        filename,
        format='png'
    )

    dot.attr(
        rankdir='LR',
        splines='spline',
        nodesep='0.5',
        ranksep='0.8'
    )

    dot.attr(
        'node',
        shape='ellipse',
        fontname='Times New Roman',
        fontsize='13'
    )

    dot.attr(
        'edge',
        fontname='Times New Roman',
        fontsize='11',
        arrowsize='0.8'
    )

    # Stable naming of observer states
    ordered_states = sorted(
        observer_states,
        key=lambda s: (
            len(s),
            tuple(
                sorted(
                    int(x.split('_')[1])
                    for x in s
                )
            )
        )
    )

    state_names = {
        state: f'q{i}'
        for i, state in enumerate(ordered_states)
    }

    # Observer states
    for state in ordered_states:

        dot.node(
            state_names[state],
            label=observer_state_label(state)
        )

    # Initial arrow
    dot.node(
        'start',
        label='',
        shape='point',
        width='0.1'
    )

    dot.edge(
        'start',
        state_names[initial_state]
    )

    # Observer transitions
    for (src, event), tgt in observer_transitions.items():

        dot.edge(
            state_names[src],
            state_names[tgt],
            label=pretty_event(event)
        )

    dot.render(
        filename,
        format='png',
        cleanup=True
    )

    display(
        Image(
            filename=f'{filename}.png'
        )
    )


