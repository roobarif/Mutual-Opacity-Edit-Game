# 9. PRETTY STATE LABEL
# ============================================================

def observer_state_label(state):

    def state_number(x):
        return int(x.split('_')[1])

    ordered = sorted(
        state,
        key=state_number
    )

    labels = []

    for x in ordered:

        n = x.split('_')[1]

        labels.append(
            f"x{n}"
        )

    return "{" + ", ".join(labels) + "}"


