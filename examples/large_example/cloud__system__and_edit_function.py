subscript_map = str.maketrans(
    "0123456789",
    "₀₁₂₃₄₅₆₇₈₉"
)

def pretty_event(event):

    if event.startswith('sigma_'):

        number = event.split('_')[1]

        return 'σ' + number.translate(
            subscript_map
        )

    return event


